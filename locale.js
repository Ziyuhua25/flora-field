export const translate = (value, lang) => lang === "zh" ? chinese.get(value) ?? value : value;

export function bindStaticCopy(document) {
  const nodes = [];
  const walker = document.createTreeWalker(document.body, 4);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const original = node.data.trim();
    if (chinese.has(original)) nodes.push([node, original, node.data]);
  }
  const attrs = [];
  for (const el of document.querySelectorAll("[aria-label], [title], [alt], meta[content]")) {
    for (const key of ["aria-label", "title", "alt", "content"]) {
      const original = el.getAttribute(key);
      if (chinese.has(original)) attrs.push([el, key, original]);
    }
  }
  const title = document.title;
  return lang => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.title = translate(title, lang);
    for (const [node, original, source] of nodes) node.data = source.replace(original, translate(original, lang));
    for (const [element, key, original] of attrs) element.setAttribute(key, translate(original, lang));
  };
}
